// Bundles and minifies the bookmarklet (source.js + extract.js) into
// src/generated/bookmarklet.js. The app fills in its own URL at runtime, so
// one build works on any host.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { BOOKMARKLET_VERSION } from '../src/bookmarklet/extract.js';

const out = await build({
  entryPoints: ['src/bookmarklet/source.js'], bundle: true, minify: true, write: false, format: 'iife', target: 'es2020',
});
const code = out.outputFiles[0].text.trim();
mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/bookmarklet.js', `// generated by scripts/build-bookmarklet.mjs, do not edit
export const BOOKMARKLET_SOURCE = ${JSON.stringify(code)};
export const BOOKMARKLET_VERSION = ${BOOKMARKLET_VERSION};
`);
console.log(`bookmarklet v${BOOKMARKLET_VERSION}: ${code.length} bytes`);
