// Minifies the bookmarklet into src/generated/bookmarklet.js. The app fills in
// its own URL at runtime, so one build works on any host.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';

const out = await build({
  entryPoints: ['src/bookmarklet/source.js'], bundle: false, minify: true, write: false, format: 'iife', target: 'es2020',
});
const code = out.outputFiles[0].text.trim();
mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/bookmarklet.js', `// generated by scripts/build-bookmarklet.mjs, do not edit\nexport const BOOKMARKLET_SOURCE = ${JSON.stringify(code)};\n`);
console.log(`bookmarklet: ${code.length} bytes`);
